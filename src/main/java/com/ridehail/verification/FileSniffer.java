package com.ridehail.verification;

/**
 * What a file really is, from its first bytes. The Content-Type a client sends proves nothing: only JPEG, PNG and PDF are accepted,
 * and only if the content says so, so a script or an archive cannot be uploaded under a picture's name.
 */
final class FileSniffer {
    private FileSniffer() {}

    /** The real content type, or null if it is not one we accept. */
    static String sniff(byte[] b) {
        if (b.length >= 3 && (b[0] & 0xFF) == 0xFF && (b[1] & 0xFF) == 0xD8 && (b[2] & 0xFF) == 0xFF) return "image/jpeg";
        if (b.length >= 8 && (b[0] & 0xFF) == 0x89 && b[1] == 'P' && b[2] == 'N' && b[3] == 'G' && b[4] == 0x0D && b[5] == 0x0A && b[6] == 0x1A && b[7] == 0x0A) {
            return "image/png";
        }
        if (b.length >= 5 && b[0] == '%' && b[1] == 'P' && b[2] == 'D' && b[3] == 'F' && b[4] == '-') return "application/pdf";
        return null;
    }
}
